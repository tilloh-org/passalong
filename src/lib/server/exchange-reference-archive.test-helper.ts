/** Edge length of the generated reference images in pixels. */
const imageEdgePixels = 8;

const pngSignature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

/**
 * Build a small, valid RGB PNG so the archive carries real image payloads instead of placeholder
 * text.
 *
 * @param {number} red - Red channel value.
 * @param {number} green - Green channel value.
 * @param {number} blue - Blue channel value.
 * @returns {Buffer} PNG bytes.
 */
function referencePng(red: number, green: number, blue: number): Buffer {
	const header = Buffer.alloc(13);
	header.writeUInt32BE(imageEdgePixels, 0);
	header.writeUInt32BE(imageEdgePixels, 4);
	header[8] = 8;
	header[9] = 2;
	const pixels = Buffer.alloc(imageEdgePixels * (1 + imageEdgePixels * 3));
	for (let row = 0; row < imageEdgePixels; row += 1) {
		const rowOffset = row * (1 + imageEdgePixels * 3);
		pixels[rowOffset] = 0;
		for (let column = 0; column < imageEdgePixels; column += 1) {
			const pixelOffset = rowOffset + 1 + column * 3;
			pixels[pixelOffset] = red;
			pixels[pixelOffset + 1] = green;
			pixels[pixelOffset + 2] = blue;
		}
	}
	return Buffer.concat([
		pngSignature,
		pngChunk('IHDR', header),
		pngChunk('IDAT', deflateSync(pixels)),
		pngChunk('IEND', Buffer.alloc(0))
	]);
}

/**
 * Wrap chunk data in the PNG chunk layout (length, type, data, CRC).
 *
 * @param {string} type - Four-character chunk type.
 * @param {Buffer} data - Chunk payload.
 * @returns {Buffer} Chunk bytes.
 */
function pngChunk(type: string, data: Buffer): Buffer {
	const typeBytes = Buffer.from(type, 'ascii');
	const chunk = Buffer.alloc(12 + data.length);
	chunk.writeUInt32BE(data.length, 0);
	typeBytes.copy(chunk, 4);
	data.copy(chunk, 8);
	chunk.writeUInt32BE(crc32(Buffer.concat([typeBytes, data])), 8 + data.length);
	return chunk;
}

/**
 * CRC-32 as required by the PNG chunk layout.
 *
 * @param {Buffer} payload - Bytes to checksum.
 * @returns {number} Unsigned CRC-32 value.
 */
function crc32(payload: Buffer): number {
	let crc = 0xffffffff;
	for (const byte of payload) {
		crc ^= byte;
		for (let bit = 0; bit < 8; bit += 1) {
			crc = crc & 1 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1;
		}
	}
	return (crc ^ 0xffffffff) >>> 0;
}

