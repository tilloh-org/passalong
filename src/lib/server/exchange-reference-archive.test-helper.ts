/**
 * Count the logical records of the reference users.
 *
 * @param {ExchangeUser[]} users - Users to count.
 * @returns {{ users: number; tenants: number; collections: number; items: number; marketDays: number; sales: number; expenses: number }} Counts.
 */
export function referenceArchiveCounts(users: ExchangeUser[]): {
	users: number;
	tenants: number;
	collections: number;
	items: number;
	marketDays: number;
	sales: number;
	expenses: number;
} {
	const collections = users.flatMap((user) => user.collections);
	const items = collections.flatMap((collection) => collection.items);
	return {
		users: users.length,
		tenants: users.length,
		collections: collections.length,
		items: items.length,
		marketDays: collections.reduce((total, collection) => total + collection.marketDays.length, 0),
		sales: items.filter((item) => item.soldAt !== null).length,
		expenses: collections.reduce((total, collection) => total + collection.expenses.length, 0)
	};
}

/**
 * Assemble the reference archive: the logical data file, every media payload and a manifest that
 * covers both with checksums and counts.
 *
 * @returns {Buffer} Complete archive bytes.
 */
export function buildReferenceArchive(): Buffer {
	const users = referenceArchiveUsers();
	const data: ExchangeData = { users };
	const dataPayload = Buffer.from(JSON.stringify(data, null, '\t'), 'utf8');
	const media = referenceMedia();
	const counts = referenceArchiveCounts(users);
	const files: Array<[string, Buffer]> = [
		[MANIFEST_ENTRY_NAME, Buffer.from('{}', 'utf8')],
		[DATA_ENTRY_NAME, dataPayload],
		...media
	];
	const manifestFiles: Record<string, { sha256: string; bytes: number }> = {};
	for (const [name, payload] of files) {
		if (name === MANIFEST_ENTRY_NAME) {
			continue;
		}
		manifestFiles[name] = {
			sha256: createHash(CHECKSUM_ALGORITHM).update(payload).digest('hex'),
			bytes: payload.length
		};
	}
	const manifest = {
		format: EXCHANGE_FORMAT_NAME,
		version: EXCHANGE_FORMAT_VERSION,
		archiveId: 'reference-archive',
		createdAt: '2026-10-18T00:00:00.000Z',
		producerId: 'passalong-reference-producer',
		counts,
		media: {
			files: media.size,
			bytes: [...media.values()].reduce((total, payload) => total + payload.length, 0)
		},
		checksumAlgorithm: CHECKSUM_ALGORITHM,
		files: manifestFiles
	};
	files[0] = [MANIFEST_ENTRY_NAME, Buffer.from(JSON.stringify(manifest, null, '\t'), 'utf8')];
	return buildZip(files);
}
